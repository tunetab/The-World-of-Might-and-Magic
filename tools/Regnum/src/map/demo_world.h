// Regnum — демонстрационный мир для тестов, снимков экрана и проверки отрисовки.
//
// ВНИМАНИЕ: это вымышленный пример, а не канон кампании. Названия государств, гильдий, провинций и персонажей
// придуманы для проверки редактора и не связаны с сюжетом «Мира Меча и Магии».
//
// Мир строится на настоящей береговой линии базовой карты операциями geo и действиями rules: 8 государств и
// 4 гильдии (одна государственная) с флагами и правителями, 65 сухопутных провинций (владельцы, расы, культуры,
// религии, ресурсы, торговля, штабы и влияние гильдий, постройки, модификаторы, гарнизоны, 3 оккупации),
// 6 морских провинций, войска и флоты (в том числе союзные), торговые маршруты, технологии с зависимостями,
// сделки, дань, отношения (войны и союзы), герои и советники. Мир проходит geo::validate и io::normalize
// без предупреждений. Построение детерминировано.
